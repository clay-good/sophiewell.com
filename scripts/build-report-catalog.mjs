#!/usr/bin/env node
// Generate the minimal tool-id/name map bundled into the report Worker.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const SOURCE = resolve(ROOT, 'data/search-corpus/corpus.json');
const TARGET = resolve(ROOT, 'report-catalog.js');
const check = process.argv.includes('--check');
const corpus = JSON.parse(await readFile(SOURCE, 'utf8'));
const names = Object.fromEntries(
  Object.entries(corpus)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, row]) => [id, row.name]),
);
const output = '// Generated by scripts/build-report-catalog.mjs. Do not edit.\n'
  + `export const REPORT_TOOL_NAMES = ${JSON.stringify(names)};\n`;

if (check) {
  let current = '';
  try { current = await readFile(TARGET, 'utf8'); } catch { /* reported below */ }
  if (current !== output) {
    console.error('report-catalog.js is stale; run node scripts/build-report-catalog.mjs');
    process.exit(1);
  }
  console.log(`report-catalog: ${Object.keys(names).length} tools current`);
} else {
  await writeFile(TARGET, output, 'utf8');
  console.log(`report-catalog: wrote ${Object.keys(names).length} tools`);
}
