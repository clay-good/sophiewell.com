#!/usr/bin/env node
// spec-v1643: a retired tile's own page, /tools/<old-id>/, redirects to the tile that replaced it.
//
// The hash link (#old-id) has redirected in the browser since spec-v915, and agents resolve the old id
// through data/id-aliases.json. The pre-rendered page did not: the build stops writing it when the tile
// leaves the catalog, and the host's single-page-application fallback then answers /tools/kings-score/
// with the home page and a 200. A search result or a bookmark for a retired tile landed on the home page
// instead of the calculator it became. Cloudflare's static-asset `_redirects` file turns each one into a
// permanent redirect to the survivor's page.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');

// Both spellings of each retired page, to the survivor's page. An alias whose canonical has no page of
// its own is left out rather than redirected somewhere that would answer with the home page again.
export function redirectLines(aliases, hasPage) {
  const lines = [];
  for (const [oldId, entry] of Object.entries(aliases || {}).sort(([a], [b]) => a.localeCompare(b))) {
    const canonical = entry && entry.canonical;
    if (!canonical || canonical === oldId || !hasPage(canonical)) continue;
    lines.push(`/tools/${oldId}/ /tools/${canonical}/ 301`);
    lines.push(`/tools/${oldId} /tools/${canonical}/ 301`);
  }
  return lines;
}

function main() {
  const { aliases } = JSON.parse(readFileSync(join(ROOT, 'data', 'id-aliases.json'), 'utf8'));
  const dist = join(ROOT, 'dist');
  const lines = redirectLines(aliases, (id) => existsSync(join(dist, 'tools', id, 'index.html')));
  writeFileSync(join(dist, '_redirects'), `# Generated by scripts/build-redirects.mjs from data/id-aliases.json.\n${lines.join('\n')}\n`);
  console.log(`build-redirects: wrote ${lines.length / 2} retired tool pages to dist/_redirects.`);
}

if (process.argv[1] && process.argv[1].endsWith('build-redirects.mjs')) main();
