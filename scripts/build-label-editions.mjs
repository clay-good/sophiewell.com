#!/usr/bin/env node
// spec-v1628 section 1 (fail closed): bundle the label-edition state into the shipped JS, so a tool
// can tell in the browser, with no fetch, whether the label a figure was read from still stands.
//
// `scripts/data/label-editions.json` stays the one maintained source: the weekly watch
// (scripts/data/watch-dailymed.mjs) renews or supersedes its rows. This script regenerates the
// importable module `lib/label-editions.js` from it, keeping only what a tool shows or decides on.
// test/unit/label-row.test.js regenerates and compares, so the two cannot drift.
//
// Run: `node scripts/build-label-editions.mjs`. Idempotent.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const STATE = join(ROOT, 'scripts', 'data', 'label-editions.json');
export const MODULE = join(ROOT, 'lib', 'label-editions.js');

const KEEP = ['label', 'splVersion', 'publishedOn', 'verifiedOn', 'validThrough', 'supersededOn', 'supersededBy'];

// Deterministic module text: rows keyed by set id, in set-id order.
export function renderModule(rows) {
  const table = {};
  for (const r of [...rows].sort((a, b) => a.setId.localeCompare(b.setId))) {
    table[r.setId] = Object.fromEntries(KEEP.filter((k) => r[k] !== undefined).map((k) => [k, r[k]]));
  }
  return (
    '// GENERATED by scripts/build-label-editions.mjs from scripts/data/label-editions.json.\n'
    + '// Do not edit by hand: the weekly label watch maintains the JSON; re-run the generator after it\n'
    + '// changes (test/unit/label-row.test.js fails on drift).\n'
    + '//\n'
    + '// spec-v1628 section 1: which version of each FDA label the tools read, when it was last\n'
    + '// confirmed, and whether the watched text has changed since. Read it through lib/label-row.js.\n'
    + '\n'
    + 'export const LABEL_EDITIONS = '
    + JSON.stringify(table, null, 2)
    + ';\n'
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(MODULE, renderModule(JSON.parse(readFileSync(STATE, 'utf8'))));
  console.log('build-label-editions: wrote lib/label-editions.js');
}
